import streamlit as st
from database import create_database, get_database_status


# ==========================================
# 페이지 설정
# ==========================================

st.set_page_config(
    page_title="스코어맨 배당 분석",
    page_icon="⚽",
    layout="wide"
)


# ==========================================
# DB 자동 생성
# ==========================================

create_database()


# ==========================================
# 제목
# ==========================================

st.title("⚽ 스코어맨 해외배당 분석")

st.caption(
    "초기배당 → 최종배당 → 실제 경기결과 분석 시스템"
)


# ==========================================
# DB 상태 확인
# ==========================================

status = get_database_status()


col1, col2 = st.columns(2)


with col1:

    st.metric(
        "경기 데이터",
        f"{status['matches']:,}건"
    )


with col2:

    st.metric(
        "배당 데이터",
        f"{status['odds']:,}건"
    )


st.divider()


# ==========================================
# 현재 상태
# ==========================================

if status["matches"] == 0:

    st.info(
        "현재 경기 데이터가 없습니다."
    )

    st.write(
        "다음 단계에서 스코어맨 경기 데이터를 "
        "자동으로 수집하도록 연결합니다."
    )

else:

    st.success(
        "DB에 경기 데이터가 있습니다."
    )


# ==========================================
# 데이터 구조 설명
# ==========================================

st.subheader("수집 예정 데이터")


data_list = [

    "경기 날짜",

    "국가",

    "리그",

    "홈팀",

    "원정팀",

    "초기 승/무/패 배당",

    "최종 승/무/패 배당",

    "배당 변동",

    "홈 득점",

    "원정 득점",

    "실제 승/무/패 결과",

    "배당 업체"

]


for item in data_list:

    st.write(
        f"✅ {item}"
    )


# ==========================================
# 분석 예정
# ==========================================

st.divider()

st.subheader(
    "배당 분석"
)

st.write(
    "초기배당과 최종배당을 실제 경기결과와 "
    "연결하여 과거 경기 통계를 계산합니다."
)


st.markdown(
    """
    **예시**

    초기 승배당 1.80~1.90

    ↓

    최종 승배당 하락

    ↓

    과거 동일 조건 경기 검색

    ↓

    승 / 무 / 패 확률 및 경기 건수 계산
    """
)
